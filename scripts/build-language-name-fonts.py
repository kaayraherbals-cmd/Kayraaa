"""
Builds tiny font files that contain only the letters of the language names shown in the language picker
(for example "বাংলা" or "ᱥᱟᱱᱛᱟᱲᱤ"), so every name is drawn in a proper font without downloading a whole script font.
Output: public/fonts/lang/<script>.woff2 and src/styles/lang-names.css. Run again after changing shared/languages.ts:
    python3 scripts/build-language-name-fonts.py
Needs: pip install fonttools brotli (build-time only; the outputs are committed).
"""
import re, subprocess, sys, tempfile, os
from collections import defaultdict
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = open(os.path.join(root, 'shared/languages.ts'), encoding='utf-8').read()
rows = re.findall(r"native: '([^']+)', script: '([^']+)'", src)
chars = defaultdict(set)
for native, script in rows:
    chars[script].update(native)

# script -> (fontsource package, subset file name part)
PKG = {
    'deva': ('noto-sans-devanagari', 'devanagari'), 'bengali': ('noto-sans-bengali', 'bengali'),
    'tamil': ('noto-sans-tamil', 'tamil'), 'telugu': ('noto-sans-telugu', 'telugu'),
    'gujarati': ('noto-sans-gujarati', 'gujarati'), 'kannada': ('noto-sans-kannada', 'kannada'),
    'malayalam': ('noto-sans-malayalam', 'malayalam'), 'gurmukhi': ('noto-sans-gurmukhi', 'gurmukhi'),
    'oriya': ('noto-sans-oriya', 'oriya'), 'nastaliq': ('noto-naskh-arabic', 'arabic'),
    'naskh': ('noto-naskh-arabic', 'arabic'), 'olchiki': ('noto-sans-ol-chiki', 'ol-chiki'),
    'meetei': ('noto-sans-meetei-mayek', 'meetei-mayek'),
}
# Urdu, Kashmiri and Sindhi names share one Arabic-script file
groups = {}
for script, cs in chars.items():
    if script == 'latin':
        continue
    key = 'arabic' if script in ('nastaliq', 'naskh') else script
    groups.setdefault(key, set()).update(cs)

css = ['/* Generated by scripts/build-language-name-fonts.py. Letters of the language names only. */']
for key, cs in sorted(groups.items()):
    pkg, part = PKG['naskh' if key == 'arabic' else key]
    path = os.path.join(root, f'node_modules/@fontsource-variable/{pkg}/files/{pkg}-{part}-wght-normal.woff2')
    font = TTFont(path)
    if 'fvar' in font:
        font = instancer.instantiateVariableFont(font, {'wght': 500})
    cmap = font.getBestCmap()
    keep = sorted(c for c in cs if ord(c) in cmap or ord(c) in (0x200c, 0x200d))
    missing = sorted(c for c in cs if ord(c) not in cmap and ord(c) not in (0x200c, 0x200d))
    if missing:
        print(f'WARNING {key}: not in font: {[hex(ord(m)) for m in missing]}', file=sys.stderr)
    with tempfile.TemporaryDirectory() as d:
        tmp = os.path.join(d, 'inst.ttf'); font.save(tmp)
        out = os.path.join(root, f'public/fonts/lang/{key}.woff2')
        subprocess.run([sys.executable, '-m', 'fontTools.subset', tmp, f'--unicodes={",".join(f"U+{ord(c):04X}" for c in keep)}', '--layout-features=*', '--flavor=woff2', f'--output-file={out}'], check=True)
    rng = ', '.join(f'U+{ord(c):04X}' for c in keep)
    css.append(f"@font-face {{ font-family: 'Kaayra Lang'; font-style: normal; font-weight: 400 700; font-display: swap; src: url('/fonts/lang/{key}.woff2') format('woff2'); unicode-range: {rng}; }}")
    print(key, os.path.getsize(out), 'bytes', len(keep), 'chars')
open(os.path.join(root, 'src/styles/lang-names.css'), 'w', encoding='utf-8').write('\n'.join(css) + '\n')
