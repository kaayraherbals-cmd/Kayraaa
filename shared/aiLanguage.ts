import { languageOf, type LangCode } from './languages.js';

/** Instruction added to Kaayra AI's rules when the visitor has chosen a language other than English. */
export function languageInstruction(code: LangCode): string {
  if (code === 'en') return '';
  const l = languageOf(code);
  return `\nLANGUAGE: The customer chose ${l.name} (${l.native}). Write the reply, follow_ups and every sentence in ${l.name}, in its own script, in natural everyday wording, unless the customer clearly writes in a different language, in which case use theirs. Keep product names, prices (₹ with digits exactly as in <data>), PIN codes and order numbers exactly as written in <data>. Keep the same rules about health, medicines and facts in every language. Set medical_concern to true whenever the question is about symptoms, a condition, medicines, dosage, pregnancy, children, allergies or any health matter, in any language.`;
}

